#!/usr/bin/env python3
"""Generate the exact distance/next-move table for cubes within five moves.

Run on the host; the target searches longer prefixes itself. Each sorted
32-bit entry packs a 23-bit (permutation << 10 | orientation) key, a 3-bit
distance, and a 4-bit move toward solved. No full-state table is generated.
"""

import argparse
from collections import deque
from pathlib import Path

DEPTH = 5
SOURCE = (
    (1, 4, 2, 0, 3, 5, 6),
    (0, 1, 2, 4, 5, 6, 3),
    (0, 2, 5, 3, 1, 4, 6),
)
TWIST = (
    (1, 2, 0, 2, 1, 0, 0),
    (0, 0, 0, 1, 2, 1, 2),
    (0, 0, 0, 0, 0, 0, 0),
)


def quarter_turn(state, face):
    p, o = state
    return (
        tuple(p[j] for j in SOURCE[face]),
        tuple((o[j] + TWIST[face][i]) % 3
              for i, j in enumerate(SOURCE[face])),
    )


def state_key(state):
    p, o = state
    permutation = 0
    for i in range(7):
        permutation = permutation * (7 - i) + sum(x < p[i] for x in p[i + 1:])
    orientation = 0
    for digit in o[:6]:
        orientation = orientation * 3 + digit
    return (permutation << 10) | orientation


def generate_entries():
    solved = (tuple(range(7)), (0,) * 7)
    # key -> (state, exact distance, next move toward solved)
    records = {0: (solved, 0, 0)}
    queue = deque([0])
    while queue:
        state, distance, _ = records[queue.popleft()]
        if distance == DEPTH:
            continue
        for face in range(3):
            child = state
            for turn in range(3):
                child = quarter_turn(child, face)
                key = state_key(child)
                if key not in records:
                    # Undo R/R2/R' with R'/R2/R, and likewise for B and D.
                    records[key] = (child, distance + 1, face * 3 + 2 - turn)
                    queue.append(key)

    counts = [0] * (DEPTH + 1)
    for state, distance, move in records.values():
        counts[distance] += 1
        if distance:
            parent = state
            for _ in range(move % 3 + 1):
                parent = quarter_turn(parent, move // 3)
            assert records[state_key(parent)][1] == distance - 1
    assert counts == [1, 9, 54, 321, 1847, 9992], counts

    return [key | (distance << 23) | (move << 26)
            for key, (_, distance, move) in sorted(records.items())]


def render_header(entries):
    lines = [
        "/* Generated by tools/gen_rubik_tail.py; do not edit by hand.",
        " * Exact distances and next moves for all 12,224 states within 5 moves.",
        " * Bits 0..22: (permutation << 10) | orientation; 23..25: distance;",
        " * 26..29: next move toward solved (R, R2, R', B, B2, B', D, D2, D').",
        " * Entries are sorted by the state key, not by the packed value.",
        " */",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "enum { RUBIK_TAIL_DEPTH = 5 };",
        "static const uint32_t rubik_tail[] = {",
    ]
    for i in range(0, len(entries), 5):
        lines.append("    " + ", ".join(f"0x{entry:08x}u" for entry in entries[i:i + 5]) + ",")
    lines.extend(["};", ""])
    return "\n".join(lines)


def render_assembly(entries):
    lines = [
        "# Generated by tools/gen_rubik_tail.py; do not edit by hand.",
        "# Same packed entries and key ordering as rubik_tail.h.",
        "# Bits 0..22: state key; 23..25: distance; 26..29: next move.",
        "    .section .rodata",
        "    .align 2",
        "    .globl rubik_asm_tail, rubik_asm_tail_end",
        "    .hidden rubik_asm_tail, rubik_asm_tail_end",
        "    .type rubik_asm_tail, @object",
        "rubik_asm_tail:",
    ]
    for i in range(0, len(entries), 5):
        lines.append("    .word " + ", ".join(f"0x{entry:08x}" for entry in entries[i:i + 5]))
    lines.extend([
        "rubik_asm_tail_end:",
        "    .size rubik_asm_tail, .-rubik_asm_tail",
        "",
    ])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the C and assembly tables")
    args = parser.parse_args()
    directory = Path(__file__).resolve().parents[1] / "src/rubik"
    entries = generate_entries()
    outputs = {"rubik_tail.h": render_header(entries),
               "rubik_tail.S": render_assembly(entries)}
    for name, content in outputs.items():
        output = directory / name
        if args.check:
            if not output.exists() or output.read_text() != content:
                raise SystemExit(f"{output} differs; run tools/gen_rubik_tail.py")
            print(f"{name} matches: 12,224 states, 48,896 bytes.")
        else:
            output.write_text(content)
            print(f"Wrote {output}: 12,224 states, 48,896 bytes.")


if __name__ == "__main__":
    main()
